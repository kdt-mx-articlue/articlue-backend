/* ==========================================================
   V004 채용공고 주간 크롤링 배치
   - JOB_POSTING 에 수집 출처/원본 ID/내용 해시 컬럼 추가 (신규·변경 공고만 재파싱)
   - 기존 시드 공고의 원본 URL 에서 출처/원본 ID 역산 (같은 공고 중복 수집 방지)
   - COMPANY / JOB_POSTING 시퀀스 (시드가 ID 를 직접 넣었으므로 MAX + 1 부터)
   - BATCH_RUN: 배치 실행 이력 (관리자 화면에서 상태 확인 / 수동 재실행)
   ========================================================== */

ALTER TABLE JOB_POSTING ADD (
    SOURCE         VARCHAR2(20),
    SOURCE_JOB_ID  VARCHAR2(50),
    CONTENT_HASH   VARCHAR2(64),
    CREATED_DATE   DATE DEFAULT SYSDATE,
    UPDATED_DATE   DATE
);

-- 시드 데이터에 같은 URL 이 일부 중복돼 있어 UNIQUE 대신 일반 인덱스 (중복 판정은 배치에서 수행)
CREATE INDEX IDX_JOB_POSTING_SOURCE ON JOB_POSTING (SOURCE, SOURCE_JOB_ID);

UPDATE JOB_POSTING
   SET SOURCE = 'WANTED',
       SOURCE_JOB_ID = REGEXP_SUBSTR(ORIGINAL_URL, 'wanted\.co\.kr/wd/([0-9]+)', 1, 1, NULL, 1)
 WHERE REGEXP_LIKE(ORIGINAL_URL, 'wanted\.co\.kr/wd/[0-9]+');

UPDATE JOB_POSTING
   SET SOURCE = 'SARAMIN',
       SOURCE_JOB_ID = REGEXP_SUBSTR(ORIGINAL_URL, 'rec_idx=([0-9]+)', 1, 1, NULL, 1)
 WHERE REGEXP_LIKE(ORIGINAL_URL, 'saramin\.co\.kr.*rec_idx=[0-9]+');

UPDATE JOB_POSTING
   SET SOURCE = 'JOBKOREA',
       SOURCE_JOB_ID = REGEXP_SUBSTR(ORIGINAL_URL, 'GI_Read/([0-9]+)', 1, 1, NULL, 1)
 WHERE REGEXP_LIKE(ORIGINAL_URL, 'jobkorea\.co\.kr.*GI_Read/[0-9]+');

DECLARE
    v_start NUMBER;
BEGIN
    SELECT NVL(MAX(COMPANY_ID), 0) + 1 INTO v_start FROM COMPANY;
    EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_COMPANY START WITH ' || v_start || ' INCREMENT BY 1 NOCACHE NOCYCLE';

    SELECT NVL(MAX(JOB_POSTING_ID), 0) + 1 INTO v_start FROM JOB_POSTING;
    EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_JOB_POSTING START WITH ' || v_start || ' INCREMENT BY 1 NOCACHE NOCYCLE';
END;
/

CREATE TABLE BATCH_RUN (
    RUN_ID         NUMBER        NOT NULL,
    JOB_NAME       VARCHAR2(50)  NOT NULL,
    TRIGGER_TYPE   VARCHAR2(20)  NOT NULL,
    STATUS         VARCHAR2(20)  NOT NULL,
    STARTED_AT     DATE          NOT NULL,
    FINISHED_AT    DATE,
    SUMMARY        CLOB,
    ERROR_MESSAGE  CLOB,
    CONSTRAINT PK_BATCH_RUN PRIMARY KEY (RUN_ID),
    CONSTRAINT CK_BATCH_RUN_STATUS CHECK (STATUS IN ('RUNNING', 'SUCCESS', 'PARTIAL', 'FAILED')),
    CONSTRAINT CK_BATCH_RUN_TRIGGER CHECK (TRIGGER_TYPE IN ('SCHEDULE', 'CATCHUP', 'MANUAL'))
);

CREATE INDEX IDX_BATCH_RUN_JOB ON BATCH_RUN (JOB_NAME, STARTED_AT);

CREATE SEQUENCE SEQ_BATCH_RUN START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
